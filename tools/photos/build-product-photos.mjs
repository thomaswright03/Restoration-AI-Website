// Writes js/product-photos.js from tools/photos/listings.json (each Home
// Depot listing's photos) and home-photos.json (which of them show the
// product in a home). Run after changing either:
//   node tools/photos/build-product-photos.mjs && npx prettier --write js/product-photos.js
import { readFileSync, writeFileSync } from "node:fs";

const here = new URL(".", import.meta.url);
const listings = JSON.parse(readFileSync(new URL("listings.json", here))).products;
const home = JSON.parse(readFileSync(new URL("home-photos.json", here))).home;

// Kohler's brand banner, not a photo of the product.
const SKIP = new Set(["IMAGE_LIFE_STYLE"]);
// How many product photos to show when a listing has none in a home.
const MAX_OTHER = 6;

const products = {};
for (const [mmn, listing] of Object.entries(listings)) {
  const picked = home[mmn] || [];
  products[mmn] = {
    listing: listing.listing,
    home: picked.map((i) => listing.images[i].path),
    other: listing.images
      .filter((im, i) => !picked.includes(i) && !SKIP.has(im.type))
      .slice(0, MAX_OTHER)
      .map((im) => im.path),
  };
}

const out =
  "// Generated by tools/photos/build-product-photos.mjs: don't edit by hand.\n" +
  "// Each product's Home Depot listing and its photos (paths on\n" +
  "// images.thdstatic.com/productImages/), split into the ones showing the\n" +
  "// product in a home and the listing's other product photos.\n" +
  "window.ProductPhotos = " +
  JSON.stringify({ products }) +
  ";\n";
writeFileSync(new URL("../../js/product-photos.js", here), out);
console.log(Object.keys(products).length + " products");
